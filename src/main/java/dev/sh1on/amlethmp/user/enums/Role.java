package dev.sh1on.amlethmp.user.enums;

/**
 * Enum class định nghĩa các <b>role (vai trò)</b> để phân quyền người dùng.
 * 
 * @author <a href="https://github.com/AdorableDandelion25">Himekawa</a>
 */
public enum Role {
    /**
     * Administrator - người dùng có quyền hạn cao nhất hệ thống.
     */
    ADMIN,

    /**
     * User - người dùng thông thường của hệ thống.
     */
    USER
}
